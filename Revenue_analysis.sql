/*
1. Total revenue generated by each city.

Business Insight:
Shows which cities generate the highest total driver revenue.
Useful for market expansion and city-wise performance analysis.
*/

select 
	d.city,
	sum(total_income) as total_revenue
from drivers as d
join earnings as e
on d.driver_id = e.driver_id
group by d.city
order by total_revenue desc

/*
2. Revenue generated by each vehicle type
Business Insight:
Identifies which vehicle category contributes the most revenue.
Useful for fleet planning and incentive allocation.

*/

select 
	v.vehicle_id,
	sum(e.total_income) as total_revenue
from drivers as d
join vehicles as v
on d.vehicle_id = v.vehicle_id
join earnings as e
on e.driver_id = e.driver_id
group by v.vehicle_id
order by total_revenue desc





/*
3. Monthly revenue trend.

Business Insight:
Tracks monthly revenue growth and seasonal demand.

*/

select
	date_trunc('month', earning_date) as month,
	sum(total_income) as total_revenue
from earnings
group by month
order by month


